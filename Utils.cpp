bool convert_path(char* src, const char* base) {
	static const char* search_term = "ROM";
	const char* relative_path = strstr(src, search_term);
	if (relative_path != NULL) {
		char buf[256];
		snprintf(buf, sizeof(buf), "%s%s", base, relative_path);
		strcpy(src, buf);
		return true;
	}
	return false;
}

